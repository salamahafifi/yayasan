export const strings: Record<Lang, StringTable> = {
  ms,
  en,
  zh,
  ta,
};

export function t(
  lang: Lang,
  key: string,
  vars?: Record<string, string | number>,
): string {
  const table = strings[lang];
  const raw =
    (table && table[key]) ||
    strings.en[key] ||
    key;
  if (!vars) return raw;
  return Object.entries(vars).reduce(
    (out, [k, v]) => out.replaceAll(`{${k}}`, String(v)),
    raw,
  );
}
